#!/usr/bin/env python3
"""Generate shared naming/alias facts; native platforms remain rule authorities.

Input is extracted public-domain IANA Zone/Link/table data, never executable code.
The frozen legacy contract IDs preserve old backups and strict alias exclusions.
"""
import argparse
import json
from pathlib import Path
import re

base = Path(__file__).resolve().parent
repo = base.parent.parent
data = json.loads((base / 'timezones/iana-zone-links.json').read_text())
legacy = set(json.loads((base / 'timezones/legacy-wire-identifiers.json').read_text()))
zones, table = set(data['zoneIDs']), set(data['tableIDs'])
# Backzone separates historical zones that the post-1970 core merges. Use it
# only for safe alias families, not to broaden the wire naming policy.
full_zones = zones | set(data['backzoneZoneIDs'])
links = {**data['links'], **data['backzoneLinks']}
all_names = full_zones | table | set(links) | set(links.values()) | legacy
assert all(re.fullmatch(r'[A-Za-z0-9._+/-]+', name) for name in all_names)

def root(name):
    seen = set()
    while name in links and name not in full_zones:
        assert name not in seen, 'IANA alias cycle'
        seen.add(name)
        name = links[name]
    # UTC/GMT are equivalent zero-offset runtime fallbacks, not extra wire IDs.
    return 'Etc/UTC' if name == 'Etc/GMT' else name

accepted = sorted(legacy | {name for name in zones | table if '/' in name and not name.startswith('Etc/')})
groups = {}
for name in all_names:
    if '/' in name or name == 'UTC':
        groups.setdefault(root(name), set()).add(name)
fallbacks = {}
for name in accepted:
    group = groups.get(root(name), {name})
    ordered = [root(name)] + sorted(group - {root(name)})
    fallbacks[name] = [name] + [candidate for candidate in ordered if candidate != name]
families = sorted({tuple([key] + sorted(group - {key})) for key, group in groups.items()
                   if len(group) > 1 and any(name in accepted for name in group)})

# Export normalization (F-02). A device may legitimately report an ID outside the
# strict wire set (GMT, US/Eastern, Asia/Chongqing). Exports map it to the wire ID
# of the same IANA zone family so one task can never block a whole backup and old
# peers can still read the file. Strict import is deliberately NOT widened: these
# spellings remain invalid on the wire. The fixed POSIX-style names below are Zones
# in this snapshot and Links in IANA `backward` since 2024b.
ZERO_OFFSET = 'UTC'
POSIX_ZONES = {
    'CET': 'Europe/Brussels', 'CST6CDT': 'America/Chicago', 'EET': 'Europe/Athens',
    'EST': 'America/Panama', 'EST5EDT': 'America/New_York', 'HST': 'Pacific/Honolulu',
    'MET': 'Europe/Brussels', 'MST': 'America/Phoenix', 'MST7MDT': 'America/Denver',
    'PST8PDT': 'America/Los_Angeles', 'WET': 'Europe/Lisbon',
}
def export_target(name):
    if name in POSIX_ZONES:
        return POSIX_ZONES[name]
    seen = set()
    while name not in accepted:
        if name in seen or name not in data['links']:
            break
        seen.add(name)
        name = data['links'][name]
    if name in ('Etc/UTC', 'Etc/GMT', 'UTC'):
        return ZERO_OFFSET
    return name if name in accepted else None
export_aliases = {}
for name in sorted(set(data['links']) | set(POSIX_ZONES) | {'Etc/GMT', 'Etc/GMT+0', 'Etc/GMT-0', 'Etc/GMT0'}):
    target = export_target(name)
    if name not in accepted and target:
        export_aliases[name] = target
for name in ('Etc/GMT', 'Etc/GMT+0', 'Etc/GMT-0', 'Etc/GMT0'):
    export_aliases[name] = ZERO_OFFSET
assert all(target in accepted for target in export_aliases.values())

def quoted(value):
    return json.dumps(value, ensure_ascii=True)

array = lambda values, indent: '\n'.join(indent + quoted(value) + ',' for value in values)
family_rows = lambda indent, open_, close_: '\n'.join(
    indent + open_ + ', '.join(quoted(name) for name in family) + close_ + ',' for family in families)
alias_rows = lambda indent, sep: '\n'.join(
    indent + quoted(name) + sep + quoted(target) + ',' for name, target in sorted(export_aliases.items()))
header = '// Generated by scripts/backup-contract/generate-timezones.py; IANA ' + data['version'] + '.\n'

swift = header + '''import Foundation

/// Wire naming policy plus IANA alias fallback. Native Foundation supplies rules.
public enum CanonicalTimeZones: Sendable {
    public static let all: Set<String> = [
''' + array(accepted, '        ') + '''
    ]
    private static let families: [[String]] = [
''' + family_rows('        ', '[', ']') + '''
    ]
    private static let fallbacks: [String: [String]] = {
        var result: [String: [String]] = [:]
        for family in families {
            for name in family where all.contains(name) { result[name] = family }
        }
        return result
    }()

    /// Device-reported IDs outside the wire set, mapped to the same IANA zone family.
    public static let exportAliases: [String: String] = [
''' + alias_rows('        ', ': ') + '''
    ]
    /// Used when a device ID has no IANA family (fixed offsets such as `GMT+08:00`).
    /// The task's instant is unchanged; only its display zone degrades, and
    /// exporters record that in the backup notes.
    public static let exportFallback = "UTC"

    /// The strict wire ID for a stored or device-reported identifier. `exact` is
    /// false only for the fallback, so export can never fail on a device's zone.
    public static func wireIdentifier(_ identifier: String) -> (identifier: String, exact: Bool) {
        if all.contains(identifier) { return (identifier, true) }
        if let alias = exportAliases[identifier] { return (alias, true) }
        return (exportFallback, false)
    }

    /// Backup notes describing every fallback, so the degradation is never silent.
    public static func exportNotes(_ notes: String, replacing identifiers: Set<String>) -> String {
        guard !identifiers.isEmpty else { return notes }
        let list = identifiers.sorted().prefix(8).joined(separator: ", ")
        let line = "时区已规范为 UTC，时刻不变：" + list
        return notes.isEmpty ? line : notes + "\\n" + line
    }

    static func runtimeIdentifier(_ identifier: String, supports: (String) -> Bool) -> String? {
        guard all.contains(identifier) else { return nil }
        if supports(identifier) { return identifier }
        return fallbacks[identifier]?.first(where: { $0 != identifier && supports($0) })
    }

    public static func timeZone(for identifier: String) -> TimeZone? {
        guard let resolved = runtimeIdentifier(identifier, supports: { TimeZone(identifier: $0) != nil }) else {
            // Not a wire ID: a locally created task keeps the zone its device reported.
            return all.contains(identifier) ? nil : TimeZone(identifier: identifier)
        }
        return TimeZone(identifier: resolved)
    }
}
'''
kotlin = header + '''package com.flash.app.data

import java.time.ZoneId

/** Wire naming policy; strict native ZoneId supplies rules, never GMT fallback. */
object CanonicalTimeZones {
    val ALL: Set<String> = setOf(
''' + array(accepted, '        ') + '''
    )
    private val families: List<List<String>> = listOf(
''' + family_rows('        ', 'listOf(', ')') + '''
    )
    private val fallbacks: Map<String, List<String>> = buildMap {
        for (family in families) for (name in family) if (name in ALL) put(name, family)
    }

    /** Device-reported IDs outside the wire set, mapped to the same IANA zone family. */
    private val exportAliases: Map<String, String> = EXPORT_ALIAS_ROWS.associate { it[0] to it[1] }

    /** Used when a device ID has no IANA family (fixed offsets such as `GMT+08:00`). */
    const val EXPORT_FALLBACK = "UTC"

    /** Strict wire ID for a stored or device-reported identifier; never fails export. */
    fun wireIdentifier(identifier: String): Pair<String, Boolean> = when {
        identifier in ALL -> identifier to true
        identifier in exportAliases -> exportAliases.getValue(identifier) to true
        else -> EXPORT_FALLBACK to false
    }

    /** Backup notes describing every fallback, so the degradation is never silent. */
    fun exportNotes(notes: String, replaced: Set<String>): String {
        if (replaced.isEmpty()) return notes
        val line = "时区已规范为 UTC，时刻不变：" + replaced.sorted().take(8).joinToString(", ")
        return if (notes.isEmpty()) line else notes + "\\n" + line
    }

    internal fun runtimeIdentifier(identifier: String, supports: (String) -> Boolean): String? {
        if (identifier !in ALL) return null
        if (supports(identifier)) return identifier
        return fallbacks[identifier]?.firstOrNull { it != identifier && supports(it) }
    }

    fun zoneId(identifier: String): ZoneId? {
        val resolved = runtimeIdentifier(identifier) { runCatching { ZoneId.of(it) }.isSuccess }
            // Not a wire ID: a locally created task keeps the zone its device reported.
            ?: return if (identifier in ALL) null else runCatching { ZoneId.of(identifier) }.getOrNull()
        return runCatching { ZoneId.of(resolved) }.getOrNull()
    }
}

private val EXPORT_ALIAS_ROWS: List<List<String>> = listOf(
''' + '\n'.join('    listOf(' + quoted(n) + ', ' + quoted(t) + '),' for n, t in sorted(export_aliases.items())) + '''
)
'''
ark = header + '''import { i18n } from '@kit.LocalizationKit';

export const CANONICAL_TIME_ZONES: string[] = [
''' + array(accepted, '  ') + '''
];
const ACCEPTED: Set<string> = new Set<string>(CANONICAL_TIME_ZONES);
const FAMILIES: string[][] = [
''' + family_rows('  ', '[', ']') + '''
];
function buildFallbacks(): Map<string, string[]> {
  const result = new Map<string, string[]>();
  FAMILIES.forEach((family: string[]) => {
    family.forEach((name: string) => { if (ACCEPTED.has(name)) result.set(name, family); });
  });
  return result;
}
const FALLBACKS: Map<string, string[]> = buildFallbacks();
const EXPORT_ALIASES: Map<string, string> = new Map<string, string>([
''' + '\n'.join('  [' + quoted(n) + ', ' + quoted(t) + '],' for n, t in sorted(export_aliases.items())) + '''
]);
// Used when a device ID has no IANA family (fixed offsets such as GMT+08:00).
export const EXPORT_FALLBACK_TIME_ZONE: string = 'UTC';

// Strict wire ID for a stored or device-reported identifier; never fails export.
export function isExactWireTimeZone(identifier: string): boolean {
  return ACCEPTED.has(identifier) || EXPORT_ALIASES.has(identifier);
}
export function wireTimeZone(identifier: string): string {
  if (ACCEPTED.has(identifier)) return identifier;
  return EXPORT_ALIASES.get(identifier) ?? EXPORT_FALLBACK_TIME_ZONE;
}
// The device's zone expressed as a wire ID; stored rows must stay strictly valid.
export function deviceTimeZone(): string {
  return wireTimeZone(i18n.getTimeZone().getID());
}
// Backup notes describing every fallback, so the degradation is never silent.
export function exportNotes(notes: string, replaced: Set<string>): string {
  if (replaced.size === 0) return notes;
  const line = '时区已规范为 UTC，时刻不变：' + Array.from(replaced).sort().slice(0, 8).join(', ');
  return notes.length === 0 ? line : notes + '\\n' + line;
}

// Native available IDs include aliases, unlike Intl.supportedValuesOf's naming
// list. Unknown IDs must never reach i18n.getTimeZone's GMT fallback.
export function runtimeTimeZone(identifier: string): string | undefined {
  if (!ACCEPTED.has(identifier)) return undefined;
  const available = new Set<string>(i18n.TimeZone.getAvailableIDs());
  const candidates = [identifier].concat(FALLBACKS.get(identifier) ?? []);
  for (let index = 0; index < candidates.length; index++) {
    const candidate = candidates[index];
    if (!available.has(candidate)) continue;
    try {
      new Intl.DateTimeFormat(undefined, { timeZone: candidate }).format(new Date(0));
      return candidate;
    } catch (_) {}
  }
  return undefined;
}
'''
outputs = {
    base / 'canonical-timezones.json': json.dumps(accepted, indent=2) + '\n',
    base / 'timezone-aliases.json': json.dumps(fallbacks, indent=2, sort_keys=True) + '\n',
    base / 'timezone-export-aliases.json': json.dumps(export_aliases, indent=2, sort_keys=True) + '\n',
    repo / 'shared/FlashKit/Sources/FlashCore/Data/CanonicalTimeZones.swift': swift,
    repo / 'android/app/src/main/java/com/flash/app/data/CanonicalTimeZones.kt': kotlin,
    repo / 'harmonyos/entry/src/main/ets/data/CanonicalTimeZones.ets': ark,
}
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for filename, body in outputs.items():
    if args.check:
        assert filename.read_text() == body, f'Regenerate {filename}'
    else:
        filename.write_text(body)
print(f"IANA {data['version']}: {len(accepted)} wire IDs; native validation required; generated files checked" if args.check
      else f"Generated IANA {data['version']}: {len(accepted)} wire IDs")

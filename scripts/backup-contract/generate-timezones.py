#!/usr/bin/env python3
"""Generate shared naming/alias facts; native platforms remain rule authorities.

Input is extracted public-domain IANA Zone/Link/table data, never executable code.
The frozen legacy contract IDs preserve old backups and strict alias exclusions.
"""
import argparse
import json
from pathlib import Path
import re

base = Path(__file__).resolve().parent
repo = base.parent.parent
data = json.loads((base / 'timezones/iana-zone-links.json').read_text())
legacy = set(json.loads((base / 'timezones/legacy-wire-identifiers.json').read_text()))
zones, table = set(data['zoneIDs']), set(data['tableIDs'])
# Backzone separates historical zones that the post-1970 core merges. Use it
# only for safe alias families, not to broaden the wire naming policy.
full_zones = zones | set(data['backzoneZoneIDs'])
links = {**data['links'], **data['backzoneLinks']}
all_names = full_zones | table | set(links) | set(links.values()) | legacy
assert all(re.fullmatch(r'[A-Za-z0-9._+/-]+', name) for name in all_names)

def root(name):
    seen = set()
    while name in links and name not in full_zones:
        assert name not in seen, 'IANA alias cycle'
        seen.add(name)
        name = links[name]
    # UTC/GMT are equivalent zero-offset runtime fallbacks, not extra wire IDs.
    return 'Etc/UTC' if name == 'Etc/GMT' else name

accepted = sorted(legacy | {name for name in zones | table if '/' in name and not name.startswith('Etc/')})
groups = {}
for name in all_names:
    if '/' in name or name == 'UTC':
        groups.setdefault(root(name), set()).add(name)
fallbacks = {}
for name in accepted:
    group = groups.get(root(name), {name})
    ordered = [root(name)] + sorted(group - {root(name)})
    fallbacks[name] = [name] + [candidate for candidate in ordered if candidate != name]
families = sorted({tuple([key] + sorted(group - {key})) for key, group in groups.items()
                   if len(group) > 1 and any(name in accepted for name in group)})

def quoted(value):
    return json.dumps(value, ensure_ascii=True)

array = lambda values, indent: '\n'.join(indent + quoted(value) + ',' for value in values)
family_rows = lambda indent, open_, close_: '\n'.join(
    indent + open_ + ', '.join(quoted(name) for name in family) + close_ + ',' for family in families)
header = '// Generated by scripts/backup-contract/generate-timezones.py; IANA ' + data['version'] + '.\n'

swift = header + '''import Foundation

/// Wire naming policy plus IANA alias fallback. Native Foundation supplies rules.
public enum CanonicalTimeZones: Sendable {
    public static let all: Set<String> = [
''' + array(accepted, '        ') + '''
    ]
    private static let families: [[String]] = [
''' + family_rows('        ', '[', ']') + '''
    ]
    private static let fallbacks: [String: [String]] = {
        var result: [String: [String]] = [:]
        for family in families {
            for name in family where all.contains(name) { result[name] = family }
        }
        return result
    }()

    static func runtimeIdentifier(_ identifier: String, supports: (String) -> Bool) -> String? {
        guard all.contains(identifier) else { return nil }
        if supports(identifier) { return identifier }
        return fallbacks[identifier]?.first(where: { $0 != identifier && supports($0) })
    }

    public static func timeZone(for identifier: String) -> TimeZone? {
        guard let resolved = runtimeIdentifier(identifier, supports: { TimeZone(identifier: $0) != nil }) else { return nil }
        return TimeZone(identifier: resolved)
    }
}
'''
kotlin = header + '''package com.flash.app.data

import java.time.ZoneId

/** Wire naming policy; strict native ZoneId supplies rules, never GMT fallback. */
object CanonicalTimeZones {
    val ALL: Set<String> = setOf(
''' + array(accepted, '        ') + '''
    )
    private val families: List<List<String>> = listOf(
''' + family_rows('        ', 'listOf(', ')') + '''
    )
    private val fallbacks: Map<String, List<String>> = buildMap {
        for (family in families) for (name in family) if (name in ALL) put(name, family)
    }

    internal fun runtimeIdentifier(identifier: String, supports: (String) -> Boolean): String? {
        if (identifier !in ALL) return null
        if (supports(identifier)) return identifier
        return fallbacks[identifier]?.firstOrNull { it != identifier && supports(it) }
    }

    fun zoneId(identifier: String): ZoneId? {
        val resolved = runtimeIdentifier(identifier) { runCatching { ZoneId.of(it) }.isSuccess } ?: return null
        return runCatching { ZoneId.of(resolved) }.getOrNull()
    }
}
'''
ark = header + '''import { i18n } from '@kit.LocalizationKit';

export const CANONICAL_TIME_ZONES: string[] = [
''' + array(accepted, '  ') + '''
];
const ACCEPTED: Set<string> = new Set<string>(CANONICAL_TIME_ZONES);
const FAMILIES: string[][] = [
''' + family_rows('  ', '[', ']') + '''
];
function buildFallbacks(): Map<string, string[]> {
  const result = new Map<string, string[]>();
  FAMILIES.forEach((family: string[]) => {
    family.forEach((name: string) => { if (ACCEPTED.has(name)) result.set(name, family); });
  });
  return result;
}
const FALLBACKS: Map<string, string[]> = buildFallbacks();

// Native available IDs include aliases, unlike Intl.supportedValuesOf's naming
// list. Unknown IDs must never reach i18n.getTimeZone's GMT fallback.
export function runtimeTimeZone(identifier: string): string | undefined {
  if (!ACCEPTED.has(identifier)) return undefined;
  const available = new Set<string>(i18n.TimeZone.getAvailableIDs());
  const candidates = [identifier].concat(FALLBACKS.get(identifier) ?? []);
  for (let index = 0; index < candidates.length; index++) {
    const candidate = candidates[index];
    if (!available.has(candidate)) continue;
    try {
      new Intl.DateTimeFormat(undefined, { timeZone: candidate }).format(new Date(0));
      return candidate;
    } catch (_) {}
  }
  return undefined;
}
'''
outputs = {
    base / 'canonical-timezones.json': json.dumps(accepted, indent=2) + '\n',
    base / 'timezone-aliases.json': json.dumps(fallbacks, indent=2, sort_keys=True) + '\n',
    repo / 'shared/FlashKit/Sources/FlashCore/Data/CanonicalTimeZones.swift': swift,
    repo / 'android/app/src/main/java/com/flash/app/data/CanonicalTimeZones.kt': kotlin,
    repo / 'harmonyos/entry/src/main/ets/data/CanonicalTimeZones.ets': ark,
}
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for filename, body in outputs.items():
    if args.check:
        assert filename.read_text() == body, f'Regenerate {filename}'
    else:
        filename.write_text(body)
print(f"IANA {data['version']}: {len(accepted)} wire IDs; native validation required; generated files checked" if args.check
      else f"Generated IANA {data['version']}: {len(accepted)} wire IDs")
